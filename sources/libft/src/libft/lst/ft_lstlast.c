#include "../../../includes/libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	if (!lst)
		return (lst);
	while (lst->next)
		lst = lst->next;
	return (lst);
}
/*
Check if lst is NULL. If yes, cancel the function.
Until there is no next element, go to the next node.
Return the last node.
*/
