#include "../../../includes/libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*list;

	list = malloc(sizeof(t_list));
	if (!list)
		return (NULL);
	list->next = NULL;
	list->content = content;
	return (list);
}
/*
Malloc and check if fail. If malloc failed, return NULL.
Initialize next to NULL and add the content to list->content.
Return the node.
*/
